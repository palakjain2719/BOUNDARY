import { z } from "zod";
import type { Competition } from "../data/types";
import type { RulesConfig } from "./types";
import legacy from "./rules/kaggle-ipl-legacy-inferred.json";
import modern from "./rules/dream11-t20-modern-draft.json";
import t20_2026 from "./rules/dream11-t20-2026.json";
import iplTab2026 from "./rules/dream11-tata-ipl-tab-2026.json";

const band = z
  .object({
    gt: z.number().optional(),
    gte: z.number().optional(),
    lt: z.number().optional(),
    lte: z.number().optional(),
    points: z.number(),
    label: z.string(),
  })
  .refine((b) => !(b.gt !== undefined && b.gte !== undefined) && !(b.lt !== undefined && b.lte !== undefined), "Band has two lower or two upper bounds");
const threshold = z.object({ at: z.number().positive(), points: z.number(), label: z.string() });
const role = z.enum(["WK", "BAT", "AR", "BOWL"]);

export const rulesSchema = z.object({
  id: z.string().min(1),
  version: z.string().regex(/^\d+\.\d+\.\d+$/),
  name: z.string(),
  competitions: z.array(z.enum(["IPL", "WPL"])).min(1),
  format: z.literal("T20"),
  effectiveFrom: z.string().nullable(),
  effectiveTo: z.string().nullable(),
  officialSourceUrl: z.string().url(),
  verifiedAt: z.string().nullable(),
  status: z.enum(["draft", "reviewed", "verified"]),
  provenance: z.string(),
  notes: z.array(z.string()),
  participation: z.object({ announcedXI: z.number(), substitutePlayed: z.number() }),
  batting: z.object({
    run: z.number(),
    boundaryBonus: z.number(),
    sixBonus: z.number(),
    milestones: z.array(threshold),
    milestoneMode: z.enum(["highest_only", "cumulative", "cumulative_top_exclusive"]),
    duck: z.number().max(0),
    duckExemptRoles: z.array(role),
  }),
  bowling: z.object({
    wicket: z.number(),
    lbwBowledBonus: z.number(),
    haulBonuses: z.array(threshold),
    haulMode: z.enum(["highest_only", "cumulative"]),
    maiden: z.number(),
    dotBall: z.number(),
  }),
  fielding: z.object({
    catch: z.number(),
    catchBonus: threshold.nullable(),
    stumping: z.number(),
    runOutDirect: z.number(),
    runOutIndirect: z.number(),
  }),
  strikeRate: z.object({ minBalls: z.number().int().positive(), exemptRoles: z.array(role), bands: z.array(band) }),
  economy: z.object({ minBalls: z.number().int().positive(), bands: z.array(band) }),
  multipliers: z.object({ captain: z.number().positive(), viceCaptain: z.number().positive() }),
  superOver: z.literal("excluded"),
}).refine((r) => r.status !== "verified" || !!r.verifiedAt, "A verified config needs verifiedAt");

/** Throws if bands within a rule overlap (a value would match two bands). */
export function assertNoBandOverlap(cfg: RulesConfig) {
  for (const [name, bands] of [
    ["strikeRate", cfg.strikeRate.bands],
    ["economy", cfg.economy.bands],
  ] as const) {
    for (let v = 0; v <= 400; v += 0.01) {
      const x = Math.round(v * 100) / 100;
      const hits = bands.filter(
        (b) =>
          (b.gt === undefined || x > b.gt) &&
          (b.gte === undefined || x >= b.gte) &&
          (b.lt === undefined || x < b.lt) &&
          (b.lte === undefined || x <= b.lte),
      );
      if (hits.length > 1) throw new Error(`${cfg.id}: ${name} value ${x} matches ${hits.length} bands`);
    }
  }
}

const ALL: RulesConfig[] = [legacy, t20_2026, iplTab2026, modern].map((r) => rulesSchema.parse(r) as RulesConfig);

export function listRules(): RulesConfig[] {
  return ALL;
}

export function getRules(id: string): RulesConfig {
  const r = ALL.find((x) => x.id === id);
  if (!r) throw new Error(`Unknown rules config ${id}`);
  return r;
}

/**
 * Default reconstruction rules per competition. The legacy config is the one with reconciliation
 * evidence against real Dream11 labels (men's IPL 2008–2023); for WPL it only produces
 * reconstructed_unverified labels. Override with RULES_DEFAULT_IPL / RULES_DEFAULT_WPL.
 */
export function defaultRulesFor(competition: Competition): RulesConfig {
  const env = competition === "IPL" ? process.env.RULES_DEFAULT_IPL : process.env.RULES_DEFAULT_WPL;
  // Current official Dream11 T20 rules (reviewed from the official page). Override per competition via env.
  return getRules(env || "dream11-t20-2026");
}

/** Rules that produced Kaggle's 2008–2023 IPL labels (used only for the legacy benchmark/reconciliation). */
export const LEGACY_RULES_ID = "kaggle-ipl-legacy-inferred";

/**
 * Label status for a score generated by the calculator. Reconstructed points stay unverified until they
 * have been validated against real platform scores, even when the rules config itself is verified.
 * Arguments are kept so a future validated (competition, rules) pair can be promoted here explicitly.
 */
export function reconstructedLabelStatus(competition: Competition, rules: RulesConfig): "reconstructed_unverified" {
  void competition;
  void rules;
  return "reconstructed_unverified";
}
